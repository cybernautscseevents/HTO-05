/**
 * Verification utility to ensure zero missing keys between English and Hindi dictionaries
 */
export function verifyTranslations(): { 
  missingInHindi: string[]; 
  totalKeys: number; 
  isValid: boolean 
} {
  const enKeys = Object.keys(en) as TranslationKey[];
  const missingInHindi: string[] = [];

  for (const key of enKeys) {
    if (!hi[key] || hi[key].trim() === '') {
      missingInHindi.push(key);
    }
  }

  const isValid = missingInHindi.length === 0;
  if (!isValid && typeof console !== 'undefined') {
    console.error(`[i18n Verification Error] Missing ${missingInHindi.length} Hindi translations:`, missingInHindi);
  }

  return {
    missingInHindi,
    totalKeys: enKeys.length,
    isValid,
  };
}
